// Turn the bots and rooms you built in the app into a room file the Rust
// engine can run.
//
// This is what lets the app drive the real engine instead of the cut-down Dart
// one: `orgbot serve` reads this file, and a bot on a subscription backend
// becomes a `cli_agent` with `mcp = true`, which is what gives it the room
// board as MCP tools alongside its own memories, skills and MCP servers.
//
// Credentials are deliberately not written here. A key is passed to the server
// through the environment instead, so a room file can be looked at, kept, or
// shared without leaking one.
//
// ignore_for_file: prefer_interpolation_to_compose_strings
library;

import 'models.dart';
import 'room_check.dart';
import 'roles.dart';

/// A room file plus the environment the server needs to run it.
class RoomFile {
  /// The TOML document.
  final String toml;

  /// Environment variables carrying any API keys, kept out of the file.
  final Map<String, String> environment;

  /// Bots that could not be included, with the reason.
  final List<String> skipped;

  const RoomFile(this.toml, this.environment, this.skipped);
}

/// Render a room and its bots as a room file.
RoomFile buildRoomFile(RoomDef room, List<BotDef> bots) {
  final buffer = StringBuffer();
  final environment = <String, String>{};
  final skipped = <String>[];

  buffer
    ..writeln('# Generated by OrgBot. Credentials are passed by environment,')
    ..writeln('# never written here.')
    ..writeln('[room]')
    ..writeln('name = ' + _s(room.name))
    ..writeln('goal = ' + _s(room.goal))
    ..writeln('completion = "all_tasks_terminal"')
    ..writeln();

  for (final bot in bots) {
    final handle = bot.handle.isEmpty ? _slug(bot.name) : _slug(bot.handle);
    if (handle.isEmpty) {
      skipped.add(bot.name + ': no usable handle');
      continue;
    }
    final role = Roles.byKey(bot.role);

    buffer
      ..writeln('[[bots]]')
      ..writeln('handle = ' + _s(handle))
      ..writeln('display_name = ' + _s(bot.name.isEmpty ? handle : bot.name))
      ..writeln('roles = [' + _s(role.key) + ']')
      ..writeln('persona = ' + _s(_persona(bot, role)));

    // Permissions come from the role, so separation of duties survives the
    // trip into the engine rather than being a UI-only idea.
    final powers = bot.powers ?? role.powers;
    buffer
      ..writeln('[bots.autonomy]')
      ..writeln('may_create_tasks = ' + powers.mayCreateTasks.toString())
      ..writeln('may_inspect = ' + powers.mayInspect.toString())
      ..writeln('may_submit = ' + powers.maySubmit.toString());

    final cli = bot.provider.cli;
    if (cli != null) {
      buffer
        ..writeln('[bots.provider]')
        ..writeln('kind = "cli_agent"')
        ..writeln('cli = ' + _s(cli.binary))
        ..writeln('model = ' + _s(bot.model))
        ..writeln('workdir = ' + _s(expandHome(room.path)))
        // The board as MCP tools, on top of the CLI's own memories, skills
        // and MCP servers.
        ..writeln('mcp = true')
        ..writeln('policy = "workspace_write"');
    } else if (bot.provider == ProviderKind.deepseek) {
      if (bot.apiKey.trim().isEmpty) {
        skipped.add('@' + handle + ': DeepSeek needs an API key');
        // Undo the partial entry rather than emit an unusable bot.
        _rollbackLastBot(buffer);
        continue;
      }
      environment['DEEPSEEK_API_KEY'] = bot.apiKey.trim();
      buffer
        ..writeln('[bots.provider]')
        ..writeln('kind = "deepseek"')
        ..writeln('model = ' +
            _s(bot.model.isEmpty ? 'deepseek-chat' : bot.model));
    } else {
      buffer
        ..writeln('[bots.provider]')
        ..writeln('kind = "scripted"')
        ..writeln('script = "I am a demo bot with no model behind me."');
    }
    buffer.writeln();
  }

  for (final task in room.tasks.where((t) => t.trim().isNotEmpty)) {
    buffer
      ..writeln('[[tasks]]')
      ..writeln('title = ' + _s(_firstLine(task)))
      ..writeln('brief = ' + _s(task))
      ..writeln();
  }

  return RoomFile(buffer.toString(), environment, skipped);
}

/// A bot's full standing instruction: its own persona plus its role's brief.
String _persona(BotDef bot, RoleDef role) {
  final own = bot.persona.trim();
  return own.isEmpty ? role.brief : own + '\n\n' + role.brief;
}

/// Drop the `[[bots]]` block currently being written, used when a bot turns
/// out to be unusable partway through.
void _rollbackLastBot(StringBuffer buffer) {
  final text = buffer.toString();
  final start = text.lastIndexOf('[[bots]]');
  if (start < 0) return;
  buffer
    ..clear()
    ..write(text.substring(0, start));
}

/// A TOML basic string. Escaping matters: a goal with a quote or a newline in
/// it would otherwise produce a file the server refuses to parse.
String _s(String value) {
  final escaped = value
      .replaceAll('\\', r'\\')
      .replaceAll('"', r'\"')
      .replaceAll('\n', r'\n')
      .replaceAll('\r', r'\r')
      .replaceAll('\t', r'\t');
  return '"' + escaped + '"';
}

/// A handle the engine will accept: lowercase, no spaces.
String _slug(String value) {
  final cleaned = value
      .trim()
      .toLowerCase()
      .replaceAll(RegExp(r'[^a-z0-9_-]+'), '-')
      .replaceAll(RegExp(r'^-+|-+$'), '');
  return cleaned;
}

String _firstLine(String text) {
  final line = text.trim().split('\n').first.trim();
  return line.length > 80 ? line.substring(0, 80) : line;
}
