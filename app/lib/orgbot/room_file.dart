// Turn the bots and rooms you built in the app into a room file the Rust
// engine can run.
//
// This is what lets the app drive the real engine instead of the cut-down Dart
// one: `orgbot serve` reads this file, and a bot on a subscription backend
// becomes a `cli_agent` with `mcp = true`, which is what gives it the room
// board as MCP tools alongside its own memories, skills and MCP servers.
//
// Credentials are deliberately not written here. A key is passed to the server
// through the environment instead, so a room file can be looked at, kept, or
// shared without leaking one.
//
// ignore_for_file: prefer_interpolation_to_compose_strings
library;

import '../engine/agent_cli.dart';
import 'credentials.dart';
import 'models.dart';
import 'room_check.dart';
import 'roles.dart';

/// A room file plus the environment the server needs to run it.
class RoomFile {
  /// The TOML document.
  final String toml;

  /// Environment variables carrying any API keys, kept out of the file.
  final Map<String, String> environment;

  /// Bots that could not be included, with the reason.
  final List<String> skipped;

  const RoomFile(this.toml, this.environment, this.skipped);
}

/// Render a room and its bots as a room file.
RoomFile buildRoomFile(
  RoomDef room,
  List<BotDef> bots, {
  Credentials? credentials,
  bool? canRunClis,
  Map<String, Object?>? workspace,
  String userName = 'You',
  String userProfile = '',
  String? statePath,
}) {
  // A CLI can only run where the binary exists. Everywhere else — a phone,
  // most obviously — the same subscription is reached through its API with
  // the token this device signed in for. Overridable so the phone path can
  // be tested from a desktop.
  final runsClis = canRunClis ?? canRunAgentClis;
  final buffer = StringBuffer();
  final environment = <String, String>{};
  final skipped = <String>[];

  buffer
    ..writeln('# Generated by OrgBot. Credentials are passed by environment,')
    ..writeln('# never written here.')
    ..writeln('[room]')
    ..writeln('name = ' + _s(room.name))
    ..writeln('goal = ' + _s(room.goal))
    ..writeln('completion = "all_tasks_terminal"')
    ..writeln();

  if (statePath != null) buffer.writeln('state_path = ${_s(statePath)}\n');

  // Interactive phone rooms keep working until completion or an explicit pause.
  // Preserve the separate CLI build's defaults and the native turn/error limits.
  // The turn budget is the room's spend control. Written explicitly so it is
  // the room's setting rather than whatever the engine defaults to, and so a
  // long-running room is not stopped once a day by a number nobody chose.
  buffer.writeln('[room.limits]');
  if (!runsClis) buffer.writeln('max_duration_ms = 0');
  buffer
    ..writeln('max_total_turns = ' + room.maxTurns.toString())
    ..writeln();

  if (!runsClis && workspace != null) {
    buffer
      ..writeln('[workspace]')
      ..writeln('label = ' + _s(workspace['label'] as String))
      ..writeln('root = ' + _s(workspace['root'] as String))
      ..writeln('writable = ${workspace['writable'] == true}')
      ..writeln('commands = ${workspace['commands'] == true}')
      ..writeln();
  }

  for (final bot in bots) {
    final handle = bot.handle.isEmpty ? _slug(bot.name) : _slug(bot.handle);
    if (handle.isEmpty) {
      skipped.add(bot.name + ': no usable handle');
      continue;
    }
    final role = Roles.byKey(bot.role);

    buffer
      ..writeln('[[bots]]')
      ..writeln('handle = ' + _s(handle))
      ..writeln('display_name = ' + _s(bot.name.isEmpty ? handle : bot.name))
      ..writeln('roles = [' + _s(role.key) + ']')
      ..writeln(
        'persona = ' +
            _s(
              '${_persona(bot, role)}\n\nThe human operating this room is ${userName.trim().isEmpty ? 'You' : userName.trim()}. Address them by that name.\n${userProfile.trim().isEmpty ? '' : 'Their self-described profile and preferences:\n${userProfile.trim()}'}\n${room.memory.trim().isEmpty ? '' : 'Pinned room memory from the owner:\n${room.memory.trim()}'}',
            ),
      );

    // Permissions come from the role, so separation of duties survives the
    // trip into the engine rather than being a UI-only idea.
    final powers = bot.powers ?? role.powers;
    buffer
      ..writeln('[bots.autonomy]')
      ..writeln('may_create_tasks = ' + powers.mayCreateTasks.toString())
      ..writeln('may_inspect = ' + powers.mayInspect.toString())
      ..writeln('may_submit = ' + powers.maySubmit.toString());

    final paired = credentials?.forProvider(bot.provider);
    final cli = bot.provider.cli;
    if (cli != null && !runsClis && !bot.provider.signsInOnDevice) {
      skipped.add(
        '@' +
            handle +
            ': ' +
            bot.provider.label +
            ' has no sign-in that works without its CLI, so it can only run '
                'on a computer',
      );
      _rollbackLastBot(buffer);
      continue;
    } else if (cli != null && !runsClis && paired != null) {
      if (bot.model.trim().isEmpty) {
        skipped.add(
          '@$handle: choose a ${bot.provider.label} model in Edit bot. The account is signed in, but no model is selected.',
        );
        _rollbackLastBot(buffer);
        continue;
      }
      // API-backed, using the paired subscription token.
      environment[bot.provider == ProviderKind.grok &&
                  paired.kind == CredentialKind.apiKey
              ? 'GROK_API_KEY'
              : credentialEnvVar(bot.provider)] =
          paired.token;
      buffer
        ..writeln('[bots.provider]')
        ..writeln('kind = ' + _s(_apiKindFor(bot.provider)))
        ..writeln('model = ' + _s(bot.model));
      if (bot.provider != ProviderKind.anthropic) {
        buffer.writeln('profile = ' + _s(bot.provider.key));
      }
    } else if (cli != null && !runsClis) {
      skipped.add(
        '@' +
            handle +
            ': ' +
            bot.provider.label +
            ' is not signed in on this device — open Sign in and approve it',
      );
      _rollbackLastBot(buffer);
      continue;
    } else if (cli != null) {
      buffer
        ..writeln('[bots.provider]')
        ..writeln('kind = "cli_agent"')
        ..writeln('cli = ' + _s(cli.binary))
        ..writeln('model = ' + _s(bot.model))
        ..writeln('workdir = ' + _s(expandHome(room.path)))
        // The board as MCP tools, on top of the CLI's own memories, skills
        // and MCP servers.
        ..writeln('mcp = true')
        ..writeln('policy = "workspace_write"');
    } else if (bot.provider.needsApiKey) {
      final key = bot.apiKey.trim().isNotEmpty
          ? bot.apiKey.trim()
          : paired?.token.trim() ?? '';
      if (key.isEmpty) {
        skipped.add('@$handle: ${bot.provider.label} needs an API key');
        // Undo the partial entry rather than emit an unusable bot.
        _rollbackLastBot(buffer);
        continue;
      }
      if (bot.provider == ProviderKind.ollama && bot.model.trim().isEmpty) {
        skipped.add('@$handle: choose an Ollama Cloud model in Edit bot');
        _rollbackLastBot(buffer);
        continue;
      }
      final shared = environment[credentialEnvVar(bot.provider)];
      buffer.writeln('[bots.provider]');
      if (bot.provider == ProviderKind.deepseek &&
          (shared == null || shared == key)) {
        environment['DEEPSEEK_API_KEY'] = key;
        buffer.writeln('kind = "deepseek"');
      } else {
        final profile =
            bot.provider == ProviderKind.ollama &&
                (shared == null || shared == key)
            ? 'ollama'
            : '${bot.provider.key}_$handle';
        final prefix = 'ORGBOT_${profile.toUpperCase().replaceAll('-', '_')}';
        environment['${prefix}_API_KEY'] = key;
        environment['${prefix}_BASE_URL'] = bot.provider.apiBaseUrl;
        buffer
          ..writeln('kind = "openai"')
          ..writeln('profile = ' + _s(profile));
      }
      buffer.writeln(
        'model = ' + _s(bot.model.isEmpty ? 'deepseek-chat' : bot.model),
      );
    } else {
      buffer
        ..writeln('[bots.provider]')
        ..writeln('kind = "scripted"')
        ..writeln('script = "I am a demo bot with no model behind me."');
    }
    buffer.writeln();
  }

  // What each role can do and who may cover for it. Emitted for the roles
  // this room's bots actually hold, so the file stays about this room rather
  // than carrying the whole catalogue.
  //
  // Without this the engine matches roles by name exactly, and work sits
  // stranded whenever the one bot holding a role is busy — which is how a
  // sixteen-bot room ended up with nine bots free and nothing moving.
  final held = <String>{
    for (final bot in bots) Roles.byKey(bot.role).key,
  };
  for (final key in held) {
    final role = Roles.byKey(key);
    if (role.capabilities.isEmpty && role.fallbacks.isEmpty) continue;
    // Only name stand-ins that are actually in this room; pointing at a role
    // nobody holds is noise in the file and does nothing.
    final present = role.fallbacks.where(held.contains).toList();
    buffer
      ..writeln('[[roles]]')
      ..writeln('name = ' + _s(role.key));
    if (role.capabilities.isNotEmpty) {
      buffer.writeln(
          'capabilities = [' + role.capabilities.map(_s).join(', ') + ']');
    }
    if (present.isNotEmpty) {
      buffer.writeln('fallbacks = [' + present.map(_s).join(', ') + ']');
    }
    buffer.writeln();
  }

  for (final task in room.tasks.where((t) => t.trim().isNotEmpty)) {
    buffer
      ..writeln('[[tasks]]')
      ..writeln('title = ' + _s(_firstLine(task)))
      ..writeln('brief = ' + _s(task))
      ..writeln();
  }

  return RoomFile(buffer.toString(), environment, skipped);
}

/// The environment variable the provider layer reads a credential from.
String credentialEnvVar(ProviderKind provider) {
  switch (provider) {
    case ProviderKind.anthropic:
      // A subscription token is an OAuth token, not an API key, and the
      // provider layer sends it as a bearer with the oauth beta header.
      return 'ANTHROPIC_AUTH_TOKEN';
    case ProviderKind.codex:
      // A ChatGPT sign-in is not an OpenAI API key: it authenticates against
      // ChatGPT's own backend, which the engine reaches through its own
      // adapter, so it travels under its own name.
      return 'CODEX_AUTH_TOKEN';
    case ProviderKind.grok:
      return 'GROK_AUTH_TOKEN';
    case ProviderKind.deepseek:
      return 'DEEPSEEK_API_KEY';
    case ProviderKind.ollama:
      return 'ORGBOT_OLLAMA_API_KEY';
    case ProviderKind.scripted:
      return '';
  }
}

/// The API-backed provider kind for a subscription, used where no CLI can run.
String _apiKindFor(ProviderKind provider) {
  switch (provider) {
    case ProviderKind.anthropic:
      return 'anthropic';
    case ProviderKind.codex:
      return 'openai';
    case ProviderKind.grok:
      return 'openai';
    default:
      return 'scripted';
  }
}

/// A bot's full standing instruction: its own persona plus its role's brief.
String _persona(BotDef bot, RoleDef role) {
  final own = bot.persona.trim();
  return own.isEmpty ? role.brief : own + '\n\n' + role.brief;
}

/// Drop the `[[bots]]` block currently being written, used when a bot turns
/// out to be unusable partway through.
void _rollbackLastBot(StringBuffer buffer) {
  final text = buffer.toString();
  final start = text.lastIndexOf('[[bots]]');
  if (start < 0) return;
  buffer
    ..clear()
    ..write(text.substring(0, start));
}

/// A TOML basic string. Escaping matters: a goal with a quote or a newline in
/// it would otherwise produce a file the server refuses to parse.
String _s(String value) {
  final escaped = value
      .replaceAll('\\', r'\\')
      .replaceAll('"', r'\"')
      .replaceAll('\n', r'\n')
      .replaceAll('\r', r'\r')
      .replaceAll('\t', r'\t');
  return '"' + escaped + '"';
}

/// A handle the engine will accept: lowercase, no spaces.
String _slug(String value) {
  final cleaned = value
      .trim()
      .toLowerCase()
      .replaceAll(RegExp(r'[^a-z0-9_-]+'), '-')
      .replaceAll(RegExp(r'^-+|-+$'), '');
  return cleaned;
}

String _firstLine(String text) {
  final line = text.trim().split('\n').first.trim();
  return line.length > 80 ? line.substring(0, 80) : line;
}
